fn schema() -> reflection::Schema<'static> {
    let opts = VerifierOptions::default();
    reflection::root_as_schema_with_opts(&opts, MINI_SCHEMA).expect("schema must be valid")
}

/// Sanity check: the embedded seed must verify and return the expected values.
#[test]
fn seed_is_valid_and_readable() {
    let schema = schema();
    let sb = SafeBuffer::new(MINI_SEED, &schema).expect("seed must verify");
    let root = sb.get_root();

    assert_eq!(root.get_any_field_integer("n").unwrap(), 7);

    let st = root.get_field_struct("st").unwrap().expect("st is present");
    assert_eq!(st.get_any_field_integer("b").unwrap(), -3);
}

/// A nested struct declared at offset 0 of its parent must not rebind the parent's
/// buffer location to the child's schema object.
///
/// `verify_struct` used `HashMap::insert`, so for `struct Outer { a: St; b: short }`
/// the child `a` resolves to the same buffer position as `Outer` -- the key the caller
/// had just mapped to `Outer`. The unconditional overwrite rebound the parent, so
/// by-name lookups on `outer` resolved against `St`.
#[test]
fn nested_struct_at_offset_zero_does_not_hijack_parent_lookup() {
    let schema = schema();
    let sb = SafeBuffer::new(MINI_SEED, &schema).expect("seed must verify");
    let root = sb.get_root();

    let outer = root.get_field_struct("st").unwrap().expect("st is present");

    // Outer's own field must resolve.
    assert_eq!(outer.get_any_field_integer("b").unwrap(), -3);

    // The child's field must not resolve against the parent.
    assert!(
        outer.get_any_field_integer("x").is_err(),
        "child field 'x' must not resolve against parent Outer"
    );
}

/// An attacker-controlled union discriminant must be range-checked before it is used to
/// index the schema's enum values.
///
/// `verify_union` called `union_enum.values().get(enum_value)` with `enum_value` read
/// straight from the buffer. `Vector::get` asserts `idx < self.len()`, so a discriminant
/// beyond the enum's value count panicked from inside the safe `SafeBuffer::new`.
#[test]
fn out_of_range_union_discriminant_is_rejected_not_panicking() {
    let schema = schema();

    let mut rejected = false;
    for i in 0..MINI_SEED.len() {
        for replacement in [0xFFu8, 0x7f, 0x05, 0x03] {
            let mut mutated = MINI_SEED.to_vec();
            mutated[i] = replacement;

            let schema_ptr: *const _ = &schema;
            let outcome = catch_unwind(AssertUnwindSafe(move || {
                // SAFETY: `schema` outlives the closure; the pointer only sidesteps the
                // borrow checker across `catch_unwind`.
                SafeBuffer::new(&mutated, unsafe { &*schema_ptr }).is_ok()
            }))
            .unwrap_or_else(|_| panic!("byte {i:#04x} = {replacement:#04x} panicked in SafeBuffer::new"));

            if !outcome {
                rejected = true;
            }
        }
    }

    assert!(rejected, "expected at least one mutation to be rejected");
}

/// Field locations derived from the buffer's vtable must be range-checked.
///
/// `get_field_loc` returned `table.loc() + field_offset` without comparing it against the
/// buffer length, and every `get_any_*` accessor reads there. With debug assertions off
/// this was an out-of-bounds heap read via the safe `SafeTable::get_any_field_string`.
/// Rather than pinning one magic byte, this asserts the general property: no single-byte
/// mutation of a schema-valid buffer may panic anywhere in the safe read path.
#[test]
fn no_single_byte_mutation_panics_in_the_safe_read_path() {
    let schema = schema();

    for i in 0..MINI_SEED.len() {
        for replacement in [0xFFu8, 0x7f, 0x05] {
            let mut mutated = MINI_SEED.to_vec();
            mutated[i] = replacement;

            let schema_ptr: *const _ = &schema;
            let outcome = catch_unwind(AssertUnwindSafe(move || {
                if let Ok(sb) = SafeBuffer::new(&mutated, unsafe { &*schema_ptr }) {
                    let root = sb.get_root();
                    for name in ["st", "u", "n"] {
                        let _ = root.get_any_field_string(name);
                        let _ = root.get_any_field_integer(name);
                        let _ = root.get_any_field_float(name);
                    }
                    if let Ok(Some(st)) = root.get_field_struct("st") {
                        for name in ["a", "b"] {
                            let _ = st.get_any_field_string(name);
                            let _ = st.get_any_field_integer(name);
                        }
                    }
                }
            }));

            assert!(
                outcome.is_ok(),
                "byte {i:#04x} = {replacement:#04x} panicked in the safe read path"
            );
        }
    }
}

/// A field lying within `size-1` bytes of the end of the buffer must not be written.
///
/// `set_any_value_integer` compared `buf.len()` against the *type size* rather than
/// checking that the value fits from the *field's location*, so a field near the end
/// of the buffer passed the check and was then written past the end of the slice:
/// `emplace_scalar` only `debug_assert!`s the available capacity, so in release builds
/// this was an out-of-bounds **write** that still returned `Ok(())`.
#[test]
fn set_scalar_near_end_of_buffer_is_rejected_not_written() {
    use flatbuffers::Table;

    const CANARY: u8 = 0xAA;

    let schema = schema();
    let root_obj = schema.objects().iter().find(|o| o.name().ends_with("Root")).unwrap();
    let fields = root_obj.fields();
    let n_field = fields.iter().find(|f| f.name() == "n").unwrap();

    let table_loc =
        u32::from_le_bytes([MINI_SEED[0], MINI_SEED[1], MINI_SEED[2], MINI_SEED[3]]) as usize;

    // SAFETY: MINI_SEED is a valid buffer built for MINI_SCHEMA.
    let table = unsafe { Table::new(MINI_SEED, table_loc) };
    let field_off = table.vtable().get(n_field.offset()) as usize;
    let field_loc = table_loc + field_off;

    // Leave only 2 bytes after the field, so an i32 write would run 2 bytes past the end.
    let logical_len = field_loc + 2;
    let mut backing = [CANARY; 256];
    backing[..logical_len].copy_from_slice(&MINI_SEED[..logical_len]);
    let before: Vec<u8> = backing[logical_len..logical_len + 16].to_vec();

    let logical: &mut [u8] = &mut backing[..logical_len];
    // SAFETY: exercising the documented setter path on a buffer whose field location
    // is deliberately near the end.
    let res = unsafe {
        flatbuffers_reflection::set_any_field_integer(logical, table_loc, &n_field, 0x1122_3344)
    };

    assert!(
        res.is_err(),
        "writing a field that does not fit must be rejected, got {res:?}"
    );

    let after: Vec<u8> = backing[logical_len..logical_len + 16].to_vec();
    assert_eq!(
        before, after,
        "bytes past the end of the buffer were modified: {before:02x?} -> {after:02x?}"
    );
}
